_IMMEDIATE_SELF_HARM_PATTERN = re.compile(
    r"\b(suicid\w*|kill myself|end my life|take my own life|self[- ]?harm|hurt myself|"
    r"harm myself|cutting myself|want to die|wish i were dead|better off dead|"
    r"don'?t want to live|no reason to live|can'?t go on|ending it all|overdose|immediate danger)\b",
    flags=re.IGNORECASE,
)

_SUPPORTIVE_CUE_PATTERN = re.compile(
    r"\b(hopeless|worthless|overwhelmed|panic attack|depress\w*|severe anxiety)\b",
    flags=re.IGNORECASE,
)


def detect_immediate_self_harm_cues(text: str) -> bool:
    """Detect explicit self-harm or immediate-danger expressions directly from input text."""
    return bool(text and _IMMEDIATE_SELF_HARM_PATTERN.search(text))


def should_show_supportive_guidance(
    text: str,
    predicted_label: str = "",
    distress_keywords: List[str] | None = None,
) -> bool:
    """Return True if crisis/distress cues appear in text or the predicted label flags distress."""
    if detect_immediate_self_harm_cues(text):
        return True
    if text and _SUPPORTIVE_CUE_PATTERN.search(text):
        return True
    if predicted_label:
        keywords = distress_keywords or [
            "distress",
            "depress",
            "anxiety",
            "stress",
            "suicid",
            "crisis",
            "risk",
        ]
        lowered = predicted_label.lower()
        return any(kw in lowered for kw in keywords)
    return False
