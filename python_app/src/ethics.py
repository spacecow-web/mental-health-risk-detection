_SUPPORTIVE_CUE_PATTERN = re.compile(
    r"\b(suicid\w*|kill myself|end my life|self[- ]?harm|hopeless|worthless|can'?t go on|"
    r"want to die|overwhelmed|panic attack|depress\w*|severe anxiety)\b",
    flags=re.IGNORECASE,
)


def should_show_supportive_guidance(
    text: str,
    predicted_label: str = "",
    distress_keywords: List[str] | None = None,
) -> bool:
    """Return True if either distress cues appear in text or the predicted label flags distress."""
    if text and _SUPPORTIVE_CUE_PATTERN.search(text):
        return True
    if predicted_label:
        keywords = distress_keywords or [
            "distress",
            "depress",
            "anxiety",
            "stress",
            "suicid",
            "crisis",
            "risk",
        ]
        lowered = predicted_label.lower()
        return any(kw in lowered for kw in keywords)
    return False
